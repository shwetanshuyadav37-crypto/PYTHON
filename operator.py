# Operator in python:-

#arithmetic operartors:-
print(5+6)
print(5-6)
print(5*6)
print(5/2)
print(5%2)
print(5//2)
print(5**2)

#relational operators:-
print(4>5)
print(4<5)
print(4>=4)
print(4<=4)
print(4==4)
print(4!=4)

#logical operators:-
print(1 and 0)
print(1 or 0)
print(not 1)

#bitwise operatoprs:-
#bitwise and:
print(2 & 3)

#bitwise or:-
print(2 | 3)

#bitwise xor:-
print (2 ^ 3)

#bitwise not:-
print(~3)

#bitwise left shift:-
print(4 >> 2)

#bitwise right shift:-
print (5 << 2)

# ASSIGNMENT OPERATORS:-
# '='
a = 2
a+= 2
print(a)

# MEMBERSHIP OPERATORS:-
# 'in' and 'not in'
print( 'R' in 'Rohit')
print(2 not in [1,2,3,4,5])